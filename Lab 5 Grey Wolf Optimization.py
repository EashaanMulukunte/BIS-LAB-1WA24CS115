# 2. Define Problem (Marketing Budget Optimization)
# ==========================================
total_budget_limit = 10000.0

def marketing_revenue_objective(allocation):
    ch0_budget, ch1_budget, ch2_budget = allocation[0], allocation[1], allocation[2]

    # Estimated revenue models for each channel
    rev_ch0 = 5.0 * np.log1p(ch0_budget) * 200
    rev_ch1 = 1.8 * (ch1_budget ** 0.8) * 10
    rev_ch2 = 3.5 * (ch2_budget ** 0.5) * 50

    total_revenue = rev_ch0 + rev_ch1 + rev_ch2

    # Constraint check
    total_spent = ch0_budget + ch1_budget + ch2_budget
    penalty = 0.0
    if total_spent > total_budget_limit:
        penalty = (total_spent - total_budget_limit) ** 2 * 1000

    return -total_revenue + penalty

# ==========================================
# 3. Execute GWO Optimization
# ==========================================
budget_gwo = GreyWolfOptimizer(
    obj_func=marketing_revenue_objective,
    num_wolves=30,
    max_iter=80,
    dim=3,
    lb=0.0,
    ub=10000.0
)

best_allocation, best_neg_revenue, _ = budget_gwo.optimize()

final_social = max(0, best_allocation[0])
final_search = max(0, best_allocation[1])
final_email = max(0, best_allocation[2])
total_spent = final_social + final_search + final_email
predicted_revenue = -best_neg_revenue

print("--- Budget Allocation Optimization Completed ---")
print(f"Optimized Social Media Budget: ${final_social:.2f}")
print(f"Optimized Search Engine Budget: ${final_search:.2f}")
print(f"Optimized Email Campaign Budget: ${final_email:.2f}")
print(f"----------------------------------------------")
print(f"Total Allocated Budget        : ${total_spent:.2f} / ${total_budget_limit:.2f}")
print(f"Expected Maximum Revenue      : ${predicted_revenue:.2f}\n")

