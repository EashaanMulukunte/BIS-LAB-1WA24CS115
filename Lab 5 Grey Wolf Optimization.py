import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# 1. Grey Wolf Optimizer Class Definition
# ==========================================
class GreyWolfOptimizer:
    def __init__(self, obj_func, num_wolves=30, max_iter=100, dim=2, lb=-5.12, ub=5.12):
        self.obj_func = obj_func
        self.num_wolves = num_wolves
        self.max_iter = max_iter
        self.dim = dim
        self.lb = np.array(lb) if isinstance(lb, list) else np.full(dim, lb)
        self.ub = np.array(ub) if isinstance(ub, list) else np.full(dim, ub)

        self.positions = np.random.uniform(self.lb, self.ub, (num_wolves, dim))

        self.alpha_pos = np.zeros(dim)
        self.alpha_score = float('inf')

        self.beta_pos = np.zeros(dim)
        self.beta_score = float('inf')

        self.delta_pos = np.zeros(dim)
        self.delta_score = float('inf')

        self.convergence_curve = []

    def optimize(self):
        for l in range(self.max_iter):
            for i in range(self.num_wolves):
                self.positions[i] = np.clip(self.positions[i], self.lb, self.ub)
                fitness = self.obj_func(self.positions[i])

                if fitness < self.alpha_score:
                    self.delta_score = self.beta_score
                    self.delta_pos = self.beta_pos.copy()
                    self.beta_score = self.alpha_score
                    self.beta_pos = self.alpha_pos.copy()
                    self.alpha_score = fitness
                    self.alpha_pos = self.positions[i].copy()
                elif fitness < self.beta_score:
                    self.delta_score = self.beta_score
                    self.delta_pos = self.beta_pos.copy()
                    self.beta_score = fitness
                    self.beta_pos = self.positions[i].copy()
                elif fitness < self.delta_score:
                    self.delta_score = fitness
                    self.delta_pos = self.positions[i].copy()

            a = 2 - l * (2 / self.max_iter)

            for i in range(self.num_wolves):
                for j in range(self.dim):
                    # Update based on Alpha
                    r1, r2 = np.random.random(), np.random.random()
                    A1 = 2 * a * r1 - a
                    C1 = 2 * r2
                    D_alpha = abs(C1 * self.alpha_pos[j] - self.positions[i, j])
                    X1 = self.alpha_pos[j] - A1 * D_alpha

                    # Update based on Beta
                    r1, r2 = np.random.random(), np.random.random()
                    A2 = 2 * a * r1 - a
                    C2 = 2 * r2
                    D_beta = abs(C2 * self.beta_pos[j] - self.positions[i, j])
                    X2 = self.beta_pos[j] - A2 * D_beta

                    # Update based on Delta
                    r1, r2 = np.random.random(), np.random.random()
                    A3 = 2 * a * r1 - a
                    C3 = 2 * r2
                    D_delta = abs(C3 * self.delta_pos[j] - self.positions[i, j])
                    X3 = self.delta_pos[j] - A3 * D_delta

                    self.positions[i, j] = (X1 + X2 + X3) / 3

            self.convergence_curve.append(self.alpha_score)

        return self.alpha_pos, self.alpha_score, self.convergence_curve

