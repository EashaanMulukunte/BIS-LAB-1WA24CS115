# ================================================================
# 5. EXECUTE ACO
# ================================================================

aco = AntColonyOptimization(
    graph=G,
    n_ants=30,
    n_iterations=100,
    alpha=1,
    beta=3,
    evaporation=0.5,
    Q=100
)

best_route, best_time = aco.optimize(
    start_node,
    destination_node
)

print("\n========== ACO OPTIMIZATION RESULT ==========")

print("Optimized Route:", " -> ".join(best_route))

print("Minimum Travel Time:",
      round(best_time, 2), "minutes")





