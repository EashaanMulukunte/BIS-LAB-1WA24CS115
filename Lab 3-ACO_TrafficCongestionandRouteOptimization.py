# 2. CREATE ROAD NETWORK
# ================================================================

G = nx.Graph()

# (Start, End, Distance_km, Speed_kmph, Congestion_Factor)

roads = [
    ('A', 'B', 4, 40, 1.2),
    ('A', 'C', 6, 50, 1.5),
    ('A', 'D', 8, 60, 1.1),
    ('B', 'C', 3, 30, 1.8),
    ('B', 'E', 5, 45, 1.2),
    ('C', 'D', 4, 40, 1.6),
    ('C', 'E', 6, 50, 1.1),
    ('C', 'F', 7, 60, 1.3),
    ('D', 'F', 3, 35, 1.2),
    ('D', 'G', 6, 50, 1.7),
    ('E', 'F', 4, 40, 1.4),
    ('E', 'H', 7, 55, 1.1),
    ('F', 'G', 5, 45, 1.2),
    ('F', 'H', 3, 30, 1.8),
    ('G', 'H', 4, 40, 1.3)
]

for u, v, distance, speed, congestion in roads:

    free_time = (distance / speed) * 60

    travel_time = free_time * congestion

    G.add_edge(
        u, v,
        distance=distance,
        speed=speed,
        congestion=congestion,
        travel_time=travel_time
    )

print("ROAD NETWORK CREATED SUCCESSFULLY")
print("Intersections:", G.number_of_nodes())
print("Roads:", G.number_of_edges())


# ================================================================
# 3. ANT COLONY OPTIMIZATION ALGORITHM
# ================================================================

class AntColonyOptimization:

    def __init__(self, graph, n_ants=30,
                 n_iterations=100, alpha=1,
                 beta=3, evaporation=0.5, Q=100):

        self.graph = graph
        self.n_ants = n_ants
        self.n_iterations = n_iterations
        self.alpha = alpha
        self.beta = beta
        self.evaporation = evaporation
        self.Q = Q

        self.pheromone = {}

        for u, v in graph.edges():
            self.pheromone[tuple(sorted((u, v)))] = 1.0

        self.best_route = None
        self.best_time = float('inf')
        self.convergence = []

    # Calculate travel time
    def get_route_time(self, route):

        total = 0

        for i in range(len(route)-1):
            total += self.graph[route[i]][route[i+1]]['travel_time']

        return total

    # Select next intersection
    def select_next_node(self, current, destination, visited):

        candidates = []

        remaining = set(self.graph.nodes()) - visited

        for neighbor in self.graph.neighbors(current):

            if neighbor in visited:
                continue

            if destination not in remaining:
                continue

            remaining_graph = self.graph.subgraph(remaining)

            if nx.has_path(remaining_graph, neighbor, destination):
                candidates.append(neighbor)

        if not candidates:
            return None

        probabilities = []

        for neighbor in candidates:

            edge = tuple(sorted((current, neighbor)))

            pheromone = self.pheromone[edge]

            travel_time = self.graph[current][neighbor]['travel_time']

            heuristic = 1 / max(travel_time, 0.001)

            probability = (
                pheromone ** self.alpha *
                heuristic ** self.beta
            )

            probabilities.append(probability)

        probabilities = np.array(probabilities, dtype=float)

        probabilities /= probabilities.sum()

        return np.random.choice(candidates, p=probabilities)

    # Construct route for one ant
    def construct_route(self, start, destination):

        current = start

        route = [start]

        visited = {start}

        for _ in range(len(self.graph.nodes())):

            if current == destination:
                return route

            next_node = self.select_next_node(
                current, destination, visited
            )

            if next_node is None:
                return None

            route.append(next_node)

            visited.add(next_node)

            current = next_node

        return None

    # Update pheromones
    def update_pheromone(self, routes):

        # Evaporation
        for edge in self.pheromone:
            self.pheromone[edge] *= (1 - self.evaporation)

        # Pheromone deposition
        for route, travel_time in routes:

            deposit = self.Q / max(travel_time, 0.001)

            for i in range(len(route)-1):

                edge = tuple(sorted((
                    route[i], route[i+1]
                )))

                self.pheromone[edge] += deposit

    # Main optimization function
    def optimize(self, start, destination):

        for iteration in range(self.n_iterations):

            routes = []

            for ant in range(self.n_ants):

                route = self.construct_route(start, destination)

                if route is None:
                    continue

                travel_time = self.get_route_time(route)

                routes.append((route, travel_time))

                if travel_time < self.best_time:

                    self.best_time = travel_time

                    self.best_route = route.copy()

            self.update_pheromone(routes)

            self.convergence.append(self.best_time)

            if (iteration + 1) % 10 == 0:

                print(
                    f"Iteration {iteration+1}: "
                    f"Best Time = {self.best_time:.2f} minutes"
                )

        return self.best_route, self.best_time


