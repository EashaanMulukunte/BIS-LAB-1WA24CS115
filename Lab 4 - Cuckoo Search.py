import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from math import gamma, sin, pi

np.random.seed(42)

# EV dataset
ev = pd.DataFrame({
    'Arrival': [8, 9, 10, 13, 17],
    'Departure': [17, 18, 19, 21, 23],
    'Capacity': [60, 75, 50, 80, 65],
    'Initial_SOC': [20, 30, 40, 25, 35],
    'Target_SOC': [90, 90, 85, 95, 90],
    'Max_Power': [11, 11, 7, 11, 7]
})

N, T = len(ev), 24
eff, station = 0.95, 30

price = np.array([
    5,5,5,5,5,6,7,9,12,14,14,12,
    10,10,11,13,15,16,15,13,10,8,7,6
])

energy = ev.Capacity.values * (
    ev.Target_SOC.values - ev.Initial_SOC.values
) / 100

# CSA parameters
nests, iterations, pa = 25, 200, 0.25
beta, alpha = 1.5, 0.05
penalty = 1e6
dim = N * T

arrival = ev.Arrival.values
departure = ev.Departure.values
power = ev.Max_Power.values

def repair(x):
    s = x.reshape(N, T).copy()

    for i in range(N):
        s[i, :arrival[i]] = 0
        s[i, departure[i]:] = 0
        s[i] = np.clip(s[i], 0, power[i])

    for t in range(T):
        total = s[:, t].sum()
        if total > station:
            s[:, t] *= station / total

    # Meet each EV's energy requirement
    for i in range(N):
        deficit = energy[i] - eff * s[i].sum()

        for t in sorted(range(arrival[i], departure[i]),
                        key=lambda t: price[t]):

            if deficit <= 1e-8:
                break

            available = min(
                power[i] - s[i, t],
                station - s[:, t].sum()
            )

            add = min(deficit / eff, max(0, available))
            s[i, t] += add
            deficit -= eff * add

    return s

def fitness(x):
    s = repair(x)
    cost = np.sum(s * price)
    unmet = np.maximum(0, energy - eff * s.sum(axis=1))
    return cost + penalty * unmet.sum()

def levy():
    sigma = (
        gamma(1 + beta) * sin(pi * beta / 2) /
        (gamma((1 + beta) / 2) * beta *
         2 ** ((beta - 1) / 2))
    ) ** (1 / beta)

    u = np.random.normal(0, sigma, dim)
    v = np.random.normal(0, 1, dim)
    return u / (np.abs(v) ** (1 / beta) + 1e-10)

# Initialize nests
X = np.random.uniform(0, 11, (nests, dim))
F = np.array([fitness(x) for x in X])

best = X[np.argmin(F)].copy()
best_fit = fitness(best)
history = []

# Cuckoo Search
for it in range(iterations):

    for i in range(nests):
        candidate = X[i] + alpha * levy() * (X[i] - best)
        candidate = np.clip(candidate, 0, 11)

        j = np.random.randint(nests)

        if fitness(candidate) < F[j]:
            X[j] = candidate.copy()
            F[j] = fitness(candidate)

    # Abandon worst nests
    worst = np.argsort(F)[-int(pa * nests):]

    for j in worst:
        X[j] = np.random.uniform(0, 11, dim)
        F[j] = fitness(X[j])

    idx = np.argmin(F)

    if F[idx] < best_fit:
        best = X[idx].copy()
        best_fit = F[idx]

    history.append(best_fit)

# Final schedule
schedule = repair(best)
delivered = eff * schedule.sum(axis=1)
final_soc = ev.Initial_SOC.values + (
    delivered / ev.Capacity.values * 100
)

cost = np.sum(schedule * price)

print("Optimal Charging Cost:", round(cost, 2))
print("Total Energy Delivered:", round(delivered.sum(), 2), "kWh")
print("Unmet Energy:", round(np.maximum(0, energy-delivered).sum(), 4), "kWh")
print("Final SOC:", np.round(final_soc, 2))

# Results table
results = pd.DataFrame({
    'EV': [f'EV{i+1}' for i in range(N)],
    'Required Energy': energy,
    'Delivered Energy': delivered,
    'Final SOC': final_soc
})
display(results.round(2))

# Charging schedule
plt.figure(figsize=(13, 5))
plt.imshow(schedule, aspect='auto', cmap='YlGnBu')
plt.colorbar(label='Charging Power (kW)')
plt.yticks(range(N), results.EV)
plt.xticks(range(T))
plt.xlabel("Hour")
plt.ylabel("Electric Vehicle")
plt.title("CSA Optimized EV Charging Schedule")
plt.show()

# Convergence graph
plt.figure(figsize=(9, 4))
plt.plot(history)
plt.xlabel("Iterations")
plt.ylabel("Best Fitness")
plt.title("Cuckoo Search Convergence")
plt.grid()
plt.show()

