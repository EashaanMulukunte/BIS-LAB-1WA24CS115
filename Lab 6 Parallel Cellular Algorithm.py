import numpy as np
import matplotlib.pyplot as plt
import pandas as pd

# =====================================================================
# 1. State Definitions & Model Functions
# =====================================================================

EMPTY = 0  # Bare ground, roads, or burned areas
TREE = 1   # Healthy trees (available fuel)
FIRE = 2   # Active fire

def initialize_forest(size, tree_density):
    forest = np.random.choice([EMPTY, TREE], size=(size, size), p=[1 - tree_density, tree_density])
    forest[size // 2, size // 2] = FIRE
    return forest

def step(forest, p_ignite):
    next_forest = forest.copy()
    size = forest.shape[0]
    burning = (forest == FIRE)

    # Neighbors burning (vectorized neighborhood evaluation)
    neighbors_burning = np.zeros_like(forest, dtype=bool)
    neighbors_burning[1:, :] |= burning[:-1, :]
    neighbors_burning[:-1, :] |= burning[1:, :]
    neighbors_burning[:, 1:] |= burning[:, :-1]
    neighbors_burning[:, :-1] |= burning[:, 1:]

    next_forest[burning] = EMPTY

    potential_ignitions = (forest == TREE) & neighbors_burning
    ignite_roll = np.random.rand(size, size) < p_ignite
    next_forest[potential_ignitions & ignite_roll] = FIRE

    return next_forest

# =====================================================================
# 2. Simulation Execution
# =====================================================================

GRID_SIZE = 60
TREE_DENSITY = 0.60
P_IGNITE = 0.55
STEPS = 80

forest_grid = initialize_forest(GRID_SIZE, TREE_DENSITY)
sim_history = [forest_grid]

for _ in range(STEPS):
    forest_grid = step(forest_grid, P_IGNITE)
    sim_history.append(forest_grid)

# =====================================================================
# 3. Static Snapshot-Based Visualization
# =====================================================================

num_snapshots = 6
snap_indices = np.linspace(0, STEPS, num_snapshots, dtype=int)

fig, axes = plt.subplots(1, num_snapshots, figsize=(18, 4))
camp = plt.cm.colors.ListedColormap(['#4a4a4a', '#2ca02c', '#ff4500'])

for idx, step_num in enumerate(snap_indices):
    ax = axes[idx]
    ax.imshow(sim_history[step_num], cmap=camp, vmin=0, vmax=2)
    ax.set_title(f"Step {step_num}")
    ax.axis('off')

plt.suptitle("Wildfire Progression Over Time (Static Snapshots)", fontsize=16, y=1.05)
plt.tight_layout()
plt.show()

# =====================================================================
# 4. Tabular Output (Compact Display & Storage)
# =====================================================================

steps_log = []
empty_counts = []
tree_counts = []
fire_counts = []

for step_idx, grid in enumerate(sim_history):
    steps_log.append(step_idx)
    empty_counts.append(np.sum(grid == EMPTY))
    tree_counts.append(np.sum(grid == TREE))
    fire_counts.append(np.sum(grid == FIRE))

df_progression = pd.DataFrame({
    'Step': steps_log,
    'Bare_or_Burnt': empty_counts,
    'Healthy_Trees': tree_counts,
    'Active_Fires': fire_counts
})

total_cells = GRID_SIZE * GRID_SIZE
df_progression['Damage_Pct'] = ((df_progression['Bare_or_Burnt'] / total_cells) * 100).round(2)

# Save tabular data
df_progression.to_csv('wildfire_progression.csv', index=False)
print("Simulation metrics saved to 'wildfire_progression.csv'.")

# Display highly compact status table (sample frames)
print("\n--- Compact Progression Summary ---")
display(df_progression.iloc[snap_indices])